def main() -> None:
    out = Path(__file__).with_name("intents.csv")
    rows: list[tuple[str, str]] = []
    seen: set[str] = set()
    for intent, queries in DATA.items():
        for q in queries:
            key = q.strip().lower()
            if key in seen:
                raise SystemExit(f"duplicate query across dataset: {q!r}")
            seen.add(key)
            rows.append((q.strip(), intent))
        if len(queries) != 40:
            raise SystemExit(f"{intent}: expected 40 queries, got {len(queries)}")
    with out.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.writer(fh)
        writer.writerow(["query", "intent"])
        writer.writerows(rows)
    print(f"wrote {len(rows)} rows to {out}")


if __name__ == "__main__":
    main()
